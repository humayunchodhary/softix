/* Build a browser bundle of @intercom/messenger-js-sdk using esbuild.
 * Run with: npm run build   (requires Node + esbuild installed as devDependency)
 *
 * A pre-built bundle already exists at dist/intercom.bundle.js so this
 * script is an optional convenience for regenerating it from source. */
const fs = require('fs');
const path = require('path');

const outDir = path.join(__dirname, 'dist');
const outFile = path.join(outDir, 'intercom.bundle.js');

if (!fs.existsSync(outDir)) fs.mkdirSync(outDir, { recursive: true });

(async () => {
  let esbuild;
  try {
    esbuild = require('esbuild');
  } catch (e) {
    console.warn('esbuild not installed — keeping existing pre-built bundle (if any).');
    if (fs.existsSync(outFile)) {
      console.log('✓ Pre-built bundle retained: dist/intercom.bundle.js');
      return;
    }
    console.error('No pre-built bundle found and esbuild unavailable. Run: npm install');
    process.exit(1);
  }

  try {
    esbuild.config = esbuild.config || {};
    await esbuild.build({
      entryPoints: [path.join(__dirname, 'intercom.entry.js')],
      bundle: true,
      minify: true,
      format: 'iife',
      outfile: outFile,
      write: true,
      banner: { js: '/* @intercom/messenger-js-sdk browser bundle — generated by build-intercom.js */' },
      define: { 'process.env.NODE_ENV': '"production"' },
    });
    console.log('✓ Built dist/intercom.bundle.js');
  } catch (e) {
    console.error('esbuild build failed:', e.message);
    process.exit(1);
  }
})();
